/**
 * samples/configurations.yaml against what it stands for: the suites under
 * suites/ (each has its arms, and its arms differ only in the dimension the
 * suite measures), the samples it names (every skill folder and document
 * exists), and the arms scripts/phase6b-smoke.sh builds and checks the
 * verdicts of (same names, toolsets, memory, skills and their loading,
 * documents, MCP servers, and the mock family's limits).
 */
import { readdir, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { ConfigurationInputSchema, SAMPLE_EXPERIMENT, SLUG_PATTERN } from '@hermes-evals/shared';
import { readSkillMetadata } from '../resources/skills/front-matter.js';
import {
  configurationInputOf,
  missingResources,
  parseSampleConfigurations,
  readSampleConfigurations,
  sampleConfigurationSpecs,
  type SampleArm,
  type SampleConfigurations,
} from './sample-configurations.js';
import { SAMPLE_MCP_SERVERS } from './seed-resources.js';

const repo = (path: string) => fileURLToPath(new URL(`../../../../${path}`, import.meta.url));
const SAMPLES = repo('samples');

/** The setting each suite varies between its arms (IMPLEMENTATION_PLAN.md 18.3). */
const DIMENSIONS: Record<string, (keyof SampleArm)[]> = {
  'invoices-v1': ['skills'],
  'mcp-v1': ['documents', 'mcp_servers'],
  'memory-v1': ['memory'],
  'knowledge-v1': ['documents', 'skills', 'skill_loading'],
  'tools-v1': ['toolsets'],
};

const load = () => readSampleConfigurations(SAMPLES);

/** One `config <name> ...` call of the smoke, as it passes the arm to POST /configurations. */
interface SmokeArm {
  name: string;
  toolsets: string;
  memory: boolean;
  skills: string;
  loading: string;
  documents: string;
  mcp: string;
  maxTurns: number;
  budget: number;
}

/** The smoke's arguments, unquoted: `'…'`, `"…"` (with \" inside) or a bare word. */
const words = (line: string): string[] =>
  [...line.matchAll(/'([^']*)'|"((?:\\.|[^"\\])*)"|(\S+)/g)].map(
    (m) => m[1] ?? (m[2] ?? m[3]!).replaceAll('\\"', '"'),
  );

async function smokeArms(): Promise<SmokeArm[]> {
  const smoke = await readFile(repo('scripts/phase6b-smoke.sh'), 'utf8');
  return smoke
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => /^config [a-z]/.test(line))
    .map((line) => {
      const [, name, toolsets, memory, skills, loading, documents, mcp, turns, budget] = words(
        line.split(' && ')[0]!,
      );
      return {
        name: name!.replace('$PREFIX-', ''),
        toolsets: toolsets!,
        memory: memory === 'true',
        skills: skills!,
        loading: loading!,
        documents: documents!,
        mcp: mcp!,
        maxTurns: Number(turns),
        budget: Number(budget),
      };
    });
}

/** The smoke's variables, by what they hold. */
async function smokeValues() {
  const smoke = await readFile(repo('scripts/phase6b-smoke.sh'), 'utf8');
  const list = (pattern: RegExp) => pattern.exec(smoke)![1]!.split(' ');
  const knowledgeDocs = (await readdir(`${SAMPLES}/documents/knowledge-v1`))
    .filter((name) => !name.startsWith('.'))
    .sort();
  return {
    toolsets: {
      $F: list(/^F='"(\w+)"'$/m),
      $FT: list(/^FT='(.*)'$/m)[0]!
        .replaceAll('"', '')
        .split(','),
      $FTC: list(/^FTC='(.*)'$/m)[0]!
        .replaceAll('"', '')
        .split(','),
    } as Record<string, string[]>,
    skills: {
      '': [],
      METHOD_SKILL: [
        /upload_skill "\$REPO_DIR\/samples\/skills\/([\w-]+)" \1\n\s*METHOD_SKILL=/.exec(
          smoke,
        )![1]!,
      ],
      KNOWLEDGE_SKILLS: list(/for SKILL in ([\w -]+); do/),
    } as Record<string, string[]>,
    documents: {
      '': [],
      MCP_DOCS: list(/for DOC in ([\w. ]+); do upload_document/).map((f) => `mcp-v1/${f}`),
      KNOWLEDGE_DOCS: knowledgeDocs.map((f) => `knowledge-v1/${f}`),
    } as Record<string, string[]>,
  };
}

/** The variable a smoke argument names, or '' for none: `"\"$METHOD_SKILL\""` is METHOD_SKILL. */
const variable = (arg: string): string[] => [...arg.matchAll(/\$([A-Z_]+)/g)].map((m) => m[1]!);

describe('samples/configurations.yaml', () => {
  it('has arms for every sample suite, and only for those', async () => {
    const file = await load();
    // The sample suites: those generated by scripts/fixtures/<suite>.ts. Suites
    // saved from the UI land in suites/ too, and have no recommended arms.
    const generators = (await readdir(repo('scripts/fixtures'))).map((f) => f.replace(/\.ts$/, ''));
    const suites = (await readdir(repo('suites'), { withFileTypes: true }))
      .filter((e) => e.isDirectory() && generators.includes(e.name))
      .map((e) => e.name)
      .sort();
    expect(Object.keys(file.suites).sort()).toEqual(suites);
    expect(Object.keys(DIMENSIONS).sort()).toEqual(suites);
    // invoices-v1's are the official experiment's (plan 19).
    expect(Object.keys(file.suites['invoices-v1']!)).toEqual(['baseline', 'with-skill']);
  });

  it("varies only each suite's dimension between its arms", async () => {
    const file = await load();
    for (const [suite, arms] of Object.entries(file.suites)) {
      const settings = Object.values(arms);
      const varying = (Object.keys(settings[0]!) as (keyof SampleArm)[]).filter((key) =>
        settings.some((arm) => JSON.stringify(arm[key]) !== JSON.stringify(settings[0]![key])),
      );
      expect([suite, varying.sort()]).toEqual([suite, [...DIMENSIONS[suite]!].sort()]);
    }
  });

  it('builds the arms the phase 6b smoke builds, with its mock limits, and 30 turns and 600 s for real', async () => {
    const file = await load();
    const smoke = await smokeArms();
    const values = await smokeValues();
    const names = Object.entries(file.suites).flatMap(([suite, arms]) =>
      Object.keys(arms).map((arm) => `${suite}-${arm}`),
    );
    expect(smoke.map((a) => a.name).sort()).toEqual([...names].sort());
    expect(smoke).toHaveLength(13);

    const servers: Record<string, string> = {
      LEDGER_VERSION: 'invoice-db',
      VENDORS_VERSION: 'vendor-directory',
    };
    for (const arm of smoke) {
      const [suite, settings] = Object.entries(file.suites).flatMap(([s, arms]) =>
        Object.entries(arms)
          .filter(([a]) => `${s}-${a}` === arm.name)
          .map(([, value]) => [s, value] as const),
      )[0]!;
      const mock = settings.limits.mock ?? file.families.mock;
      const real = settings.limits.real ?? file.families.real;
      expect({
        suite,
        toolsets: settings.toolsets,
        memory: settings.memory,
        skills: settings.skills,
        loading: settings.skill_loading,
        documents: [...settings.documents].sort(),
        mcp: [...settings.mcp_servers].sort(),
        mock: [mock.max_turns, mock.time_budget_s],
        real: [real.max_turns, real.time_budget_s],
      }).toEqual({
        suite: arm.name.slice(0, suite.length),
        toolsets: values.toolsets[arm.toolsets],
        memory: arm.memory,
        skills: variable(arm.skills).flatMap((v) => values.skills[v]!),
        loading: arm.loading,
        documents: variable(arm.documents)
          .flatMap((v) => values.documents[v]!)
          .sort(),
        mcp: variable(arm.mcp)
          .map((v) => servers[v]!)
          .sort(),
        mock: [arm.maxTurns, arm.budget],
        real: [30, 600],
      });
    }
  });

  it('names only samples that exist: skill folders by their SKILL.md name, documents, the two servers', async () => {
    const file = await load();
    const arms = Object.values(file.suites).flatMap((arms) => Object.values(arms));
    for (const name of new Set(arms.flatMap((a) => a.skills))) {
      const skillMd = await readFile(`${SAMPLES}/skills/${name}/SKILL.md`);
      expect(readSkillMetadata(skillMd).name.value).toBe(name);
    }
    for (const path of new Set(arms.flatMap((a) => a.documents))) {
      await expect(readFile(`${SAMPLES}/documents/${path}`)).resolves.toBeInstanceOf(Buffer);
    }
    const servers = new Set(arms.flatMap((a) => a.mcp_servers));
    expect([...servers].sort()).toEqual(SAMPLE_MCP_SERVERS.map((s) => s.name).sort());
    // Every document of a suite's folder reaches the arm that attaches documents.
    const visible = async (dir: string) =>
      (await readdir(dir)).filter((name) => !name.startsWith('.'));
    for (const suite of await visible(`${SAMPLES}/documents`)) {
      const files = (await visible(`${SAMPLES}/documents/${suite}`)).map((f) => `${suite}/${f}`);
      const attached = arms.filter((a) => a.documents.some((d) => d.startsWith(`${suite}/`)));
      expect(attached.map((a) => [...a.documents].sort())).toEqual([files.sort()]);
    }
  });

  it('expands to 26 saveable configurations, real and mock, the sample experiment among them', async () => {
    const file = await load();
    const specs = sampleConfigurationSpecs(file);
    expect(specs).toHaveLength(26);
    const placeholder = (names: string[]) => new Map(names.map((n) => [n, `id-${n}`]));
    const arms = Object.values(file.suites).flatMap((arms) => Object.values(arms));
    const ids = {
      skills: placeholder(arms.flatMap((a) => a.skills)),
      documents: placeholder(arms.flatMap((a) => a.documents)),
      mcpServerVersions: placeholder(arms.flatMap((a) => a.mcp_servers)),
    };
    const inputs = specs.map((spec) => configurationInputOf(file, spec, ids));
    for (const input of inputs) {
      expect(ConfigurationInputSchema.safeParse(input).success, input.name).toBe(true);
      expect(input.name).toMatch(SLUG_PATTERN);
    }
    const byName = new Map(inputs.map((input) => [input.name, input]));
    expect(byName.get(SAMPLE_EXPERIMENT.baseline)).toMatchObject({
      provider: 'custom',
      baseUrl: 'http://mock-model:8090/v1',
      model: 'mock/scripted',
      skillIds: [],
    });
    expect(byName.get(SAMPLE_EXPERIMENT.candidate)).toMatchObject({
      provider: 'custom',
      skillIds: ['id-invoice-method'],
    });
    expect(byName.get('invoices-v1-with-skill')).toMatchObject({
      provider: 'nous',
      baseUrl: null,
      model: 'openai/gpt-6.1-sol',
      maxTurns: 30,
      timeBudgetS: 600,
    });
    expect(byName.get('memory-v1-memory-on-mock')).toMatchObject({ memoryEnabled: true });
    expect(byName.get('knowledge-v1-skills-on-demand')).toMatchObject({
      skillLoading: 'on_demand',
    });
  });

  it('reports what an arm names and the seed could not find', async () => {
    const file = await load();
    const spec = sampleConfigurationSpecs(file).find((s) => s.name === 'mcp-v1-with-mcp-mock')!;
    const none = { skills: new Map(), documents: new Map(), mcpServerVersions: new Map() };
    expect(missingResources(spec, none)).toEqual([
      'MCP server invoice-db',
      'MCP server vendor-directory',
    ]);
    expect(() => configurationInputOf(file, spec, none)).toThrow(/no MCP server invoice-db/);
  });

  it('refuses an unknown key and a document not named <suite>/<file>', () => {
    const base = (arm: string) =>
      `families:\n  real: {provider: nous, model: m, max_turns: 30, time_budget_s: 600}\n` +
      `  mock: {provider: custom, base_url: 'http://mock-model:8090/v1', model: m, max_turns: 10, time_budget_s: 180}\n` +
      `suites:\n  s:\n    a: ${arm}\n`;
    const parsed: SampleConfigurations = parseSampleConfigurations(base('{toolsets: [file]}'));
    expect(parsed.suites['s']!['a']).toMatchObject({ memory: false, skill_loading: 'preload' });
    expect(() => parseSampleConfigurations(base('{toolsets: [file], memroy: true}'))).toThrow(
      /at suites\.s\.a/,
    );
    expect(() =>
      parseSampleConfigurations(base('{toolsets: [file], documents: [invoices.csv]}')),
    ).toThrow(/<suite>\/<file>/);
  });
});
